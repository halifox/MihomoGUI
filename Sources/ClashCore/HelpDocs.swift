    case "dns/index.md": scope = "dns."
    case "inbound/tun.md": scope = "tun."
    case "sniff/index.md": scope = "sniffer."
    default: scope = ""
    }
    if !scope.isEmpty, !key.hasPrefix(scope), let text = documentedFieldHelp[document + "|" + scope + key] { return text }
