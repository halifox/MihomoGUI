require 'json'
require 'pathname'
root = ARGV[0] || '/Users/user/IdeaProjects/Meta-Docs-main/docs/config'
result = {}
def clean_help(body, relative)
  body = body.gsub(/```.*?```/m, '').gsub(/<!--.*?-->/m, '').gsub(/^!!![^\n]*\n/, '').gsub(/^\#{1,6}[^\n]*\n/, '')
  body = body.gsub(/\[([^\]]+)\]\(([^)]+)\)/) do
    label, target = $1, $2
    if target.start_with?('http://', 'https://', '#')
      target = 'https://wiki.metacubex.one/config/' + relative.sub(/(?:index)?\.md$/, '') + target if target.start_with?('#')
    else
      target = Pathname.new(File.join(File.dirname(relative), target)).cleanpath.to_s
      target = 'https://wiki.metacubex.one/config/' + target.sub(/index\.md/, '').sub(/\.md/, '/')
    end
    "[#{label}](#{target})"
  end
  paragraphs = body.lines.map(&:strip).join("\n").strip.split(/\n\s*\n/).reject(&:empty?)
  paragraphs.take(4).join("\n\n")
end
files = ['general.md', 'dns/index.md', 'sniff/index.md', 'inbound/tun.md', 'inbound/port.md', 'rules/index.md', 'rule-providers/index.md']
files += Dir.glob(File.join(root, '{proxies,proxy-groups}/**/*.md')).map { |file| file.sub(root + '/', '') }.reject { |file| file =~ /\.(en|ru)\.md$/ }
files.each do |relative|
  next unless File.file?(File.join(root, relative))
  text = File.read(File.join(root, relative))
  text.scan(/^\#{2,5}\s+([^\n]+)\n(.*?)(?=^\#{2,5}\s|\z)/m).each do |heading, body|
    info = clean_help(body, relative)
    title = heading.gsub(/`|\{[^}]*\}/, '').strip.downcase
    result[relative + '|' + title] = info if !info.empty? && title =~ /^[a-z][\w.-]*$/
    body.scan(/(.*?)```[^\n]*\n(.*?)```/m).each do |prefix, code|
      nearby = clean_help(prefix, relative)
      nearby = info if nearby.empty?
      code.scan(/^\s*(?:#\s*)?([a-z][\w-]*):/).each do |match|
        result[relative + '|' + match[0]] ||= nearby unless nearby.empty?
      end
    end
    body.scan(/```[^\n]*\n(.*?)```/m).each do |block|
      lines = block[0].lines
      lines.each_with_index do |line, index|
        next unless line =~ /^\s*([a-z][\w-]*):/
        key = $1
        comments = []
        lines[(index + 1)..-1].each do |following|
          break unless following =~ /^\s*#\s*(.+)/
          note = $1.strip
          break if note =~ /^[a-z][\w-]*:/
          comments << note
        end
        result[relative + '|' + key] ||= clean_help(comments.join("\n"), relative) unless comments.empty?
      end
    end
  end
end
